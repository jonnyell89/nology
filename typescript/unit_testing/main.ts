// Different types of testing:

// E2E, or End to End.
// Tests every possible workflow on the application.
// Slow, unreliable and hard to maintain.

// Integration testing
// Ensures that an entire, integrated system meets a set of requirements.

// Unit testing
// The process of checking small pieces of code to ensure that individual parts of the program work properly on their own.
// Fast, reliable and maintainable.

// Unit testing:

// Tests an individual 'unit of code'.
// Doesn't test how different parts work together.

// End to End Testing, E2E.

// Ene to End is a type of testing that validates an entire user journey works as expected.
// User journey refers to the actions a user can make, like purchase a product or comment on a post.
// Tests are performed from the end user's perspective, so it comes closest to simulating a real user's experience.

// Tests from a user's perspective
// Expands test coverage
// Ensures correctness of entire application
// Reduces risk
// Reduces cost
// Catches bugs

// Automation testers write E2E tests:
// Test planning: Specifies key tasks, associated schedule, and resources.
// Test design: Test specificationsm test case generation, risk analysis, usage analysis, and schedulling tests.
// Test execution: Executes test cases and documents testing results.
// Results analysis: Analyses test results, evaluate testing, and perform additional testing if necessary.
